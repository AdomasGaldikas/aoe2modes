def test_ram_combined_native_voice_queue_does_not_overlap_or_repeat(ram):
    graph = [t for t in ram[2].trigger_manager.triggers
             if t.name.startswith(("RAM Scorpion voice —", "RAM Scorpion voice cooldown —",
                                   "RAM Center voice —", "RAM Center voice cooldown",
                                   "RAM Center status cooldown"))]
    metadata = json.loads((ram[0].directory / "assets/audio/manifest.json").read_text())["clips"]
    variables = {188: 0, 205: 1, 206: 0,
                 **{207 + c: 1 for c in range(8)}, **{189 + c: c + 1 for c in range(8)}}
    enabled = {t.trigger_id: bool(t.enabled) for t in graph}
    activated = {t.trigger_id: 0 for t in graph}
    sounds = []
    for now in range(180):
        for trigger in graph:
            if not enabled[trigger.trigger_id]:
                continue
            ready = True
            for condition in trigger.conditions:
                if condition.condition_type == ConditionId.TIMER:
                    ready &= now - activated[trigger.trigger_id] >= condition.timer
                else:
                    assert condition.condition_type == ConditionId.VARIABLE_VALUE
                    assert condition.comparison == Comparison.EQUAL
                    ready &= variables.get(condition.variable, 0) == condition.quantity
            if not ready:
                continue
            for effect in trigger.effects:
                if effect.effect_type == EffectId.CHANGE_VARIABLE:
                    assert effect.operation == Operation.SET
                    variables[effect.variable] = effect.quantity
                elif effect.effect_type == EffectId.PLAY_SOUND:
                    sounds.append((now, effect.source_player, effect.sound_name))
                elif effect.effect_type == EffectId.ACTIVATE_TRIGGER:
                    enabled[effect.trigger_id] = True
                    activated[effect.trigger_id] = now
                else:
                    assert effect.effect_type == EffectId.SEND_CHAT
            if not trigger.looping:
                enabled[trigger.trigger_id] = False
    assert len(sounds) == 8 * 8 + 8 + 8
    moments = sorted({(time, name) for time, _, name in sounds})
    assert len(moments) == 17
    for (before, name), (after, _) in zip(moments, moments[1:], strict=False):
        # Audio is wall time, while the native queue runs in game seconds.
        # Even standard Fast (2x) cannot start the next line over this clip.
        assert after - before >= metadata[f"{name}.wav"]["seconds"] * 2 + 1
    for owner in range(1, 9):
        sound = f"ram_center_kills_{owner:02d}_v2"
        assert [(target, name) for _, target, name in sounds if name == sound] == [(owner, sound)]
    assert variables[188] == 0 and variables[206] == 0
    assert all(variables[189 + c] == 0 for c in range(8))


def test_ram_signals_use_synchronized_selection_and_private_native_recipients(ram):
    scenario = ram[2]
    graph = scenario.trigger_manager.triggers
    press = [t for t in graph if t.name.startswith("RAM Signal select — ")]
    release = [t for t in graph if t.name.startswith("RAM Signal release — ")]
    hear = [t for t in graph if t.name.startswith("RAM Signal hear — ")]
    assert len(press) == len(release) == 64 * 8
    assert len(hear) == 24 * 4 * 8
    references = set()
    for trigger in press:
        color, event, owner = map(int, re.findall(r"\d+", trigger.name))
        assert trigger.enabled and not trigger.looping
        native, active, selection = trigger.conditions
        assert (native.variable, native.quantity) == (40 + color - 1, owner)
        assert (active.variable, active.quantity) == (32 + color - 1, 1)
        assert selection.condition_type == ConditionId.OBJECT_SELECTED_MULTIPLAYER
        assert selection.source_player == owner and selection.inverted == 0
        references.add(selection.unit_object)
        request, rearm = trigger.effects
        assert request.message == f"ramSignalSelectP{color}E{event}"
        reset = graph[rearm.trigger_id]
        assert not reset.enabled and not reset.looping
        deselect, = reset.conditions
        assert deselect.condition_type == ConditionId.OBJECT_SELECTED_MULTIPLAYER
        assert deselect.unit_object == selection.unit_object
        assert deselect.source_player == owner and deselect.inverted == 1
        assert reset.effects[0].trigger_id == trigger.trigger_id
    assert len(references) == 64
    units = {u.reference_id: u for group in scenario.unit_manager.units for u in group}
    assert all(units[ref].unit_const == 598 for ref in references)
    assert references <= {u.reference_id for u in scenario.unit_manager.units[0]}
    protect = next(t for t in graph if t.name == "RAM — protect team signal posts")
    for kind in (EffectId.DISABLE_UNIT_ATTACKABLE, EffectId.DISABLE_OBJECT_DELETION,
                 EffectId.ENABLE_OBJECT_SELECTION, EffectId.CHANGE_OBJECT_NAME):
        protected = {ref for e in protect.effects if e.effect_type == kind for ref in e.selected_object_ids}
        assert references <= protected
    for trigger in hear:
        event, color, owner = map(int, re.findall(r"\d+", trigger.name))
        target = (event - 1) % 8 + 1
        target_team = target <= 4
        assert (color <= 4) == (not target_team if 9 <= event <= 16 else target_team)
        _, event_gate, ack, occupied, native = trigger.conditions
        assert (event_gate.variable, event_gate.quantity) == (223, event)
        assert (ack.variable, ack.quantity) == (224 + color - 1, 0)
        assert (occupied.variable, occupied.quantity) == (121 + color - 1, 1)
        assert (native.variable, native.quantity) == (40 + color - 1, owner)
        voice, chat, acknowledge = trigger.effects
        assert voice.effect_type == EffectId.PLAY_SOUND and voice.source_player == owner
        assert voice.global_sound and chat.source_player == owner
        assert chat.message.startswith("[TEAM] ")
        assert (acknowledge.variable, acknowledge.quantity) == (224 + color - 1, 1)


def test_ram_signal_emitted_xs_and_native_graph(ram, tmp_path):
    compiler = shutil.which("g++")
    if compiler is None:
        pytest.skip("RAM signal execution harness requires g++")
    scenario = ram[2]
    source = next(t for t in scenario.trigger_manager.triggers if t.name == "XS SCRIPT").effects[0].message
    signals = source.split("// RAM_SIGNALS_BEGIN", 1)[1].split("// RAM_SIGNALS_END", 1)[0]
    signals = signals.split("\n", 1)[1]
    signals = re.sub(
        r"rule ramSignalHeartbeat\s+active\s+minInterval 1\s*\{\s*ramSignalHousekeeping\(\);\s*\}",
        "", signals,
    )
    signals = re.sub(
        r"for \((\w+) = ([^;]+); (<|<=) ((?:[^()]|\([^()]*\))+)\)",
        r"for (int \1 = \2; \1 \3 \4; ++\1)", signals,
    )
    signals += "\n" + "\n".join(re.findall(r"(?:void|bool) ramSignal\w+\(\) \{[^\n]+", source))
    (tmp_path / "ram-signals.h").write_text(signals)
    graph = [t for t in scenario.trigger_manager.triggers if t.name.startswith((
        "RAM Signal ", "RAM Team signal voice cooldown", "RAM Scorpion voice —",
        "RAM Scorpion voice cooldown —", "RAM Center voice —", "RAM Center voice cooldown",
        "RAM Center status cooldown",
    ))]
    native = []
    check_calls, effect_calls = {}, {}
    for trigger in graph:
        checks = []
        for c in trigger.conditions:
            if c.condition_type == ConditionId.TIMER:
                checks.append(f"{{0,{c.timer},0,0}}")
            elif c.condition_type == ConditionId.VARIABLE_VALUE:
                assert c.comparison == Comparison.EQUAL and not c.inverted
                checks.append(f"{{1,{c.variable},{c.quantity},0}}")
            elif c.condition_type == ConditionId.OBJECT_SELECTED_MULTIPLAYER:
                checks.append(f"{{2,{c.source_player},{c.unit_object},{int(bool(c.inverted))}}}")
                if trigger.name.startswith("RAM Signal select"):
                    color, event, _ = map(int, re.findall(r"\d+", trigger.name))
                    native.append(f"post[{color}][{event}]={c.unit_object};")
            else:
                assert c.condition_type == ConditionId.SCRIPT_CALL
                identifier = check_calls.setdefault(c.xs_function, len(check_calls))
                checks.append(f"{{3,{identifier},0,0}}")
        effects = []
        for index in trigger.effect_order:
            e = trigger.effects[index]
            if e.effect_type == EffectId.CHANGE_VARIABLE:
                assert e.operation == Operation.SET
                effects.append(f'{{0,{e.variable},{e.quantity},""}}')
            elif e.effect_type == EffectId.MODIFY_VARIABLE_BY_VARIABLE:
                assert e.operation == Operation.SET
                effects.append(f'{{1,{e.variable},{e.variable2},""}}')
            elif e.effect_type == EffectId.SCRIPT_CALL:
                identifier = effect_calls.setdefault(e.message, len(effect_calls))
                effects.append(f'{{2,{identifier},0,""}}')
            elif e.effect_type == EffectId.ACTIVATE_TRIGGER:
                effects.append(f'{{3,{e.trigger_id},0,""}}')
            elif e.effect_type == EffectId.PLAY_SOUND:
                effects.append(f"{{4,{e.source_player},0,{json.dumps(e.sound_name)}}}")
            else:
                assert e.effect_type == EffectId.SEND_CHAT
                effects.append(f"{{5,{e.source_player},0,{json.dumps(e.message)}}}")
        native.append(
            f"graph.push_back(Trigger{{{trigger.trigger_id},{int(bool(trigger.looping))},"
            f"{int(bool(trigger.enabled))},0,{{{','.join(checks)}}},{{{','.join(effects)}}}}});"
        )
    (tmp_path / "ram-signals-native.h").write_text("\n".join(native))
    (tmp_path / "ram-signal-calls.h").write_text(
        "bool checkScript(int id) { switch(id) {" + "".join(
            f"case {identifier}:return {name}();" for name, identifier in check_calls.items()
        ) + "default:assert(false);return false;}}\nvoid callScript(int id) {switch(id){" + "".join(
            f"case {identifier}:{name}();break;" for name, identifier in effect_calls.items()
        ) + "default:assert(false);}}\n"
    )
    manifest = json.loads((ram[0].directory / "assets/audio/manifest.json").read_text())["clips"]
    (tmp_path / "ram-voice-durations.h").write_text("\n".join(
        f"durations[{json.dumps(Path(name).stem)}]={clip['seconds']};" for name, clip in manifest.items()
    ))
    executable = tmp_path / "ram-signals"
    result = subprocess.run(
        [compiler, "-std=c++17", "-O0", "-I", str(tmp_path),
         str(Path(__file__).with_name("ram_signals_runtime.cpp")), "-o", str(executable)],
        capture_output=True, text=True, timeout=180,
    )
    assert result.returncode == 0, result.stderr
    result = subprocess.run([str(executable)], capture_output=True, text=True, timeout=30)
    assert result.returncode == 0, result.stderr
    assert "RAM team signal contracts passed" in result.stdout
