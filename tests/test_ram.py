def test_ram_native_backup_queue_broadcasts_without_xs(ram):
    """Replay the serialized queue's native timer/variable graph, without XS."""
    graph = [t for t in ram[2].trigger_manager.triggers
             if t.name.startswith(("RAM Scorpion voice —", "RAM Scorpion voice cooldown —"))]
    assert len(graph) == 16
    variables = {188: 0, **{207 + c: 1 for c in range(8)}}
    enabled = {t.trigger_id: bool(t.enabled) for t in graph}
    activated = {t.trigger_id: 0 for t in graph}
    sounds = []
    for now in range(100):
        for trigger in graph:
            if not enabled[trigger.trigger_id]:
                continue
            ready = True
            for condition in trigger.conditions:
                if condition.condition_type == ConditionId.TIMER:
                    ready &= now - activated[trigger.trigger_id] >= condition.timer
                else:
                    assert condition.condition_type == ConditionId.VARIABLE_VALUE
                    assert condition.comparison == Comparison.EQUAL
                    ready &= variables[condition.variable] == condition.quantity
            if not ready:
                continue
            for effect in trigger.effects:
                if effect.effect_type == EffectId.CHANGE_VARIABLE:
                    assert effect.operation == Operation.SET
                    variables[effect.variable] = effect.quantity
                elif effect.effect_type == EffectId.PLAY_SOUND:
                    sounds.append((now, effect.source_player, effect.sound_name))
                elif effect.effect_type == EffectId.ACTIVATE_TRIGGER:
                    enabled[effect.trigger_id] = True
                    activated[effect.trigger_id] = now
                else:
                    assert effect.effect_type == EffectId.SEND_CHAT
            enabled[trigger.trigger_id] = False
    assert len(sounds) == 64
    last = -100
    for color in range(1, 9):
        played = [(time, audience) for time, audience, name in sounds
                  if name == f"ram_scorpion_p{color}_v3"]
        assert sorted(audience for _, audience in played) == list(range(1, 9))
        assert len({time for time, _ in played}) == 1
        moment = played[0][0]
        assert moment - last >= 6
        last = moment
    assert variables[188] == 0
    assert all(variables[207 + c] == 3 for c in range(8))


