def test_ram_double_click_keeps_villagers_together_and_other_types_separate(ram):
    from AoE2ScenarioParser.datasets.heroes import HeroInfo
    from AoE2ScenarioParser.datasets.trigger_lists import ObjectAttribute
    from AoE2ScenarioParser.datasets.units import UnitInfo

    source = next(t for t in ram[2].trigger_manager.triggers if t.name == "XS SCRIPT").effects[0].message
    main = source.split("void main() {", 1)[1].split("rule cbaColorArmySpawns", 1)[0]
    attribute = int(ObjectAttribute.RUN_PATTERN)
    default = f"xsEffectAmount(cSetAttribute, objectId, {attribute}, 255, worldPlayer);"
    assert main.count(default) == 1
    assert "for (worldPlayer = 1; <= xsGetNumPlayers())" in main
    assert "for (objectId = 0; < objectCount)" in main
    overrides = re.findall(
        rf"if \(objectCount > (\d+)\) xsEffectAmount\(cSetAttribute, (\d+), "
        rf"{attribute}, (\d+), worldPlayer\);",
        main,
    )
    villagers = {unit.ID for unit in UnitInfo.vils()}
    assert len(overrides) == len(villagers)
    assert {int(unit) for _, unit, _ in overrides} == villagers
    assert all(bound == unit and int(group) == 1 for bound, unit, group in overrides)
    assert main.index(default) < main.index("// Male/female villagers")
    # Every Run Pattern write is accounted for: no hidden class-wide override can
    # accidentally mix cavalry, Heroes, signal posts or other civilian units.
    army = f"xsEffectAmount(cSetAttribute, {HeroInfo.GENGHIS_KHAN.ID}, {attribute}, 2, worldPlayer);"
    assert main.count(army) == 1
    assert len(re.findall(rf"xsEffectAmount\(cSetAttribute, [^,]+, {attribute},", main)) == 2 + len(villagers)


