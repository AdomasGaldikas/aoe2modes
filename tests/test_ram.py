def test_ram_center_emitted_runtime(ram, tmp_path):
    compiler = shutil.which("g++")
    if compiler is None:
        pytest.skip("RAM XS execution harness requires g++")
    scenario = ram[2]
    source = next(t for t in scenario.trigger_manager.triggers if t.name == "XS SCRIPT").effects[0].message
    center = source.split("// RAM_CENTER_BEGIN", 1)[1].split("// RAM_CENTER_END", 1)[0]
    center = center.split("\n", 1)[1]
    center = re.sub(
        r"rule ramCenterHeartbeat\s+active\s+minInterval 1\s*\{\s*ramCenterTick\(\);\s*\}", "", center,
    )
    center = re.sub(r"\bvector\b", "Vec", center)
    # XS string concatenation converts numbers; C++ requires explicit casts.
    center = re.sub(r'(ramName\(\w+, )("Team [^"]+")', r'\1string(\2)', center)
    center = re.sub(r'\+ xsTriggerVariable\((\d+)\)',
                    r'+ std::to_string(xsTriggerVariable(\1))', center)
    center = re.sub(
        r"for \((\w+) = ([^;]+); (<|<=) ((?:[^()]|\([^()]*\))+)\)",
        r"for (int \1 = \2; \1 \3 \4; ++\1)", center,
    )
    # Execute the guards too, including both bounds of each Hero band.
    center += "\n" + "\n".join(re.findall(r"bool ramHeroCredit\d+\(\) \{[^\n]+", source))
    center += source.split("// RAM_CENTER_NOTICES_BEGIN", 1)[1].split(
        "// RAM_CENTER_NOTICES_END", 1,
    )[0].split("\n", 1)[1]
    center += "\n" + "\n".join(re.findall(r"void ramCenterNoticeP\d+\(\) \{[^\n]+", source))
    (tmp_path / "ram-center.h").write_text(center)
    native = ["void nativeCenterRewards() {"]
    for trigger in scenario.trigger_manager.triggers:
        if not trigger.name.startswith("RAM Center kills — "):
            continue
        _, owner_gate, active_gate, pending_gate = trigger.conditions
        award, notice, voice, clear = trigger.effects
        native.append(
            f"if (variables[{owner_gate.variable}] == {owner_gate.quantity} "
            f"&& variables[{active_gate.variable}] == {active_gate.quantity} "
            f"&& variables[{pending_gate.variable}] >= {pending_gate.quantity}) {{ "
            f"kills[nativeToWorld({award.source_player})] += variables[{award.variable}]; "
            f"for (localPlayer = 0; localPlayer <= 8; ++localPlayer) {notice.message}(); "
            f"variables[{voice.variable}] = variables[{voice.variable2}]; "
            f"variables[{clear.variable}] = {clear.quantity}; }}"
        )
    native.append("}")
    (tmp_path / "ram-native.h").write_text("\n".join(native))
    initial = []
    for color, group in enumerate(scenario.unit_manager.units):
        for unit in group:
            initial.append(
                f"objects[{unit.reference_id}] = Object{{owners[{color}], {unit.unit_const}, "
                f"930, 70, 100, Vec({unit.x}, {unit.y}, -1)}};"
            )
    (tmp_path / "ram-initial.h").write_text("\n".join(initial))
    executable = tmp_path / "ram-center"
    result = subprocess.run(
        [compiler, "-std=c++17", "-O2", "-I", str(tmp_path),
         str(Path(__file__).with_name("ram_center_runtime.cpp")), "-o", str(executable)],
        capture_output=True, text=True, timeout=60,
    )
    assert result.returncode == 0, result.stderr
    result = subprocess.run([str(executable)], capture_output=True, text=True, timeout=30)
    assert result.returncode == 0, result.stderr
    assert "RAM center contracts passed" in result.stdout


