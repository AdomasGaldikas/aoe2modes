        assert bundle.read(f"resources/_common/scenario/{spec.output_name}") == scenario_path.read_bytes()
        for name, metadata in manifest["files"].items():
            content = bundle.read(name)
            assert (folder / name).read_bytes() == content
            assert hashlib.sha256(content).hexdigest() == metadata["sha256"]
            if name.endswith(".wem"):
                assert content == bundle.read(name[:-4] + ".wav")
        with wave.open(io.BytesIO(bundle.read("resources/_common/drs/sounds/ram_startup_v1.wav"))) as audio:
            assert (audio.getnchannels(), audio.getsampwidth(), audio.getframerate()) == (1, 2, 48000)
            assert 0.5 < audio.getnframes() / audio.getframerate() < 1.0
            assert any(audio.readframes(audio.getnframes()))


