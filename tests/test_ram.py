def test_ram_preserves_frozen_normal_ra_gameplay_when_center_is_disabled(repo, tmp_path):
    # Keep the original parity guarantee runnable alongside the intentional center
    # changes. Disable just that feature in a temporary copy, never in real sources.
    original = registry.get("ram", repo)
    directory = tmp_path / "ram"
    shutil.copytree(original.directory, directory)
    config = directory / "mode.toml"
    config.write_text(config.read_text().replace("enabled = true", "enabled = false"))
    spec = load_mode_spec(directory)
    result = build_mode(spec, out_dir=tmp_path / "baseline", repo=repo)
    scenario = AoE2DEScenario.from_file(str(result.output))
    reference = json.loads((spec.directory / "provenance.json").read_text())
    data = snapshot(scenario)
    probe, = [i for i, trigger in enumerate(data["triggers"])
              if trigger["name"] == "RAM — custom startup audio"]
    data["triggers"].pop(probe)
    data["display_order"] = [i - (i > probe) for i in data["display_order"] if i != probe]
    messages = data.pop("messages")
    for trigger in data["triggers"]:
        if trigger["name"] == "XS SCRIPT":
            for factory, effect in trigger["effects"]:
                if factory == "script_call":
                    effect["message"] = "\n".join(
                        line for line in effect["message"].split("\n")
                        if not line.startswith("// Generated by aoe2modes for ")
                    )
    serialized = json.dumps(data, sort_keys=True, separators=(",", ":"), default=str).encode()
    assert hashlib.sha256(serialized).hexdigest() == reference["normal_ra_gameplay_sha256"]
    expected_messages = reference["normal_ra_messages"].copy()
    expected_messages["history"] = expected_messages["history"].replace(
        "CBA Hero 4v4: RA v1.9", f"CBA Hero 4v4: RAM v{spec.version}",
    )
    expected_messages["victory"] = expected_messages["victory"].replace("RA VICTORY", "RAM VICTORY")
    assert messages == expected_messages


